"""v4sup -- detached, winner-agnostic phase supervisor skeleton (task SYS-03).

No LLM is in this package's runtime loop (package 10 S4; package 08 S7; package 13 "final state
generated by scripts"). Every decision here -- whether a phase may start, whether it finished, and
what the current state is -- comes from a deterministic check of a file, a hash, an exit code, or
a resource reading. It fails closed throughout: an empty, missing, malformed or NaN-containing
result is never reported as success, an unreadable GPU query means busy, and an ambiguous disk
reading is never treated as "enough room."

Modules:
  errors     -- shared exception types.
  paths      -- workspace-containment ("no output path can escape the workspace", T44).
  hashing    -- sha256 file hashing for prerequisite gate files.
  registry   -- the phase registry: JSON schema, loader, validation.
  gate       -- prerequisite gate-file checks (existence + hash).
  gpu        -- fail-closed GPU ownership check (nvidia-smi).
  disk       -- the two disk thresholds (refuse floor, pause target).
  artifacts  -- expected-output-artifact validation, incl. strict JSON / NaN refusal (T45).
  status     -- atomic status file + append-only event log; heartbeat != completion.
  runner     -- the Supervisor: ties the above into one phase attempt / one registry pass.
  probe      -- read-only one-line JSON status probe for the lead.
  cli        -- `python -B -m v4sup.cli {run,probe} ...`

This package only ever writes inside a workspace root explicitly given to it, plus its own logs;
it never touches the server or a GPU on its own, never installs anything, and spawns no agents.
"""
