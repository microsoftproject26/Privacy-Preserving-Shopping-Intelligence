"""List every importable package in the stage code folders, for pyproject.toml.

setuptools reads `[tool.setuptools] packages` and `[tool.setuptools.package-dir]` as static
TOML, so the mapping is pasted into pyproject.toml. This script generates it from the
folders, so it cannot drift:

    uv run python tools/list_packages.py           # print the generated TOML
    uv run python tools/list_packages.py --write   # rewrite the generated block in pyproject.toml
    uv run python tools/list_packages.py --check   # exit 1 when pyproject.toml is out of date
    uv run python tools/list_packages.py --names   # one importable name per line
    uv run python tools/list_packages.py --import  # import every name from the installed environment

The stage folders carry descriptive names (`central_trainer`, `federated_core`), but the packages
keep the import names of the old flat code tree (`v4train`, `fl`), which the hash-pinned research
code imports itself by. The import name of each top-level folder is the inverse of
`ppsi_paths.FOLDER_NAMES` (loaded from `00_common/code` by path, so the script runs before the
environment is installed, as CI does).

What counts as a package, in each `<stage>/code` folder:

* A folder with `__init__.py` is a package. Its subfolders are its subpackages, including
  implicit namespace subpackages (subfolders that hold `.py` files but no `__init__.py`,
  such as `ppsi.data`).
* A folder without `__init__.py` whose import name is a package defined in another stage
  (`ppsi`, `experiment_extensions`) is a container: each subfolder is the subpackage
  `<name>.<sub>`.
* Any other folder without `__init__.py` is a script folder run by path
  (`export_feasibility_check`, `tau_fixed_reruns`) or the byte-locked snapshot that `ppsi_env`
  puts on `sys.path` itself (`pilot_code_snapshot`). Those are not installed.
* Loose `.py` files are top-level modules (`ppsi_env`), except the `g0_*.py` scripts.

The prototype imports its scripts as the package `scripts` (`00_common/code/scripts`, a
compatibility package). Each folder in a `<stage>/scripts/prototype` folder is the subpackage
`scripts.<folder>`. The loose modules there and in `tools/` (`scripts.training_smoke`,
`scripts.generate_training_artifact_manifest`) are found through `scripts.__path__`, because
setuptools can map a package to one folder only.

The script uses only the standard library.
"""

from __future__ import annotations

import argparse
import re
import sys
import tomllib
from fnmatch import fnmatch
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
PYPROJECT = REPO_ROOT / "pyproject.toml"
CODE_GLOB = "0*/code"
SCRIPTS_GLOB = "0*/scripts/prototype"
SCRIPTS_PACKAGE = "scripts"
SCRIPT_GLOBS = ("g0_*.py",)
SKIP_DIRS = {"__pycache__"}
BEGIN = "# BEGIN generated by tools/list_packages.py: do not edit by hand"
END = "# END generated by tools/list_packages.py"

# ppsi_paths is loaded from the source tree (00_common/code), not from the installed environment,
# so --check runs before `uv sync`, as the CI workflow does.
sys.path.insert(0, str(REPO_ROOT / "00_common" / "code"))
import ppsi_paths

# folder name in the stage layout -> import name of the old flat code tree
IMPORT_NAMES = {new: old for old, new in ppsi_paths.FOLDER_NAMES.items()}


def _import_name(folder: Path) -> str:
    """The name a top-level code folder is imported by (its descriptive name when it never had
    an old one, e.g. `ppsi`)."""
    return IMPORT_NAMES.get(folder.name, folder.name)


def _code_folders() -> list[Path]:
    return sorted(p for p in REPO_ROOT.glob(CODE_GLOB) if p.is_dir())


def _scripts_folders() -> list[Path]:
    return sorted(p for p in REPO_ROOT.glob(SCRIPTS_GLOB) if p.is_dir())


def _subdirs(folder: Path) -> list[Path]:
    return sorted(
        p for p in folder.iterdir()
        if p.is_dir() and p.name not in SKIP_DIRS and not p.name.startswith(".")
    )


def _is_package(folder: Path) -> bool:
    return (folder / "__init__.py").is_file()


def _has_modules(folder: Path) -> bool:
    return any(folder.glob("*.py"))


def _walk(folder: Path, name: str, out: dict[str, Path]) -> None:
    if name in out:
        raise SystemExit(f"package {name} is defined twice: {out[name]} and {folder}")
    out[name] = folder
    for sub in _subdirs(folder):
        if _is_package(sub) or _has_modules(sub):
            _walk(sub, f"{name}.{sub.name}", out)


def discover() -> tuple[dict[str, Path], dict[str, Path], list[str]]:
    """Return (packages, top-level modules, notes about what was skipped)."""
    folders = _code_folders()
    top_level = {_import_name(d) for f in folders for d in _subdirs(f) if _is_package(d)}
    packages: dict[str, Path] = {}
    modules: dict[str, Path] = {}
    notes: list[str] = []
    for code in folders:
        for d in _subdirs(code):
            name = _import_name(d)
            if _is_package(d):
                _walk(d, name, packages)
            elif name in top_level:
                for sub in _subdirs(d):
                    if _is_package(sub) or _has_modules(sub):
                        _walk(sub, f"{name}.{sub.name}", packages)
            else:
                notes.append(f"not installed (no __init__.py, run by path): {_rel(d)}/")
        for f in sorted(code.glob("*.py")):
            if any(fnmatch(f.name, g) for g in SCRIPT_GLOBS):
                notes.append(f"not installed (script): {_rel(f)}")
            else:
                modules[f.stem] = f
    if SCRIPTS_PACKAGE in packages:
        for scripts in _scripts_folders():
            for sub in _subdirs(scripts):
                if _is_package(sub) or _has_modules(sub):
                    _walk(sub, f"{SCRIPTS_PACKAGE}.{sub.name}", packages)
    roots = {f.parent for f in modules.values()}
    if len(roots) > 1:
        raise SystemExit(
            "top-level modules live in more than one folder, but package-dir has only one \"\" "
            f"entry: {sorted(_rel(r) for r in roots)}"
        )
    return dict(sorted(packages.items())), dict(sorted(modules.items())), notes


def _rel(path: Path) -> str:
    return path.relative_to(REPO_ROOT).as_posix()


def expected() -> dict:
    packages, modules, _ = discover()
    package_dir = {}
    if modules:
        package_dir[""] = _rel(next(iter(modules.values())).parent)
    package_dir.update({name: _rel(path) for name, path in packages.items()})
    return {"packages": list(packages), "py-modules": list(modules), "package-dir": package_dir}


def render() -> str:
    exp = expected()
    lines = [BEGIN, "[tool.setuptools]", "packages = ["]
    lines += [f'    "{name}",' for name in exp["packages"]]
    lines.append("]")
    lines.append("py-modules = [" + ", ".join(f'"{m}"' for m in exp["py-modules"]) + "]")
    lines += ["", "[tool.setuptools.package-dir]"]
    width = max(len(name) for name in exp["package-dir"]) + 2
    for name, path in exp["package-dir"].items():
        key = f'"{name}"'
        lines.append(f'{key:<{width}} = "{path}"')
    lines.append(END)
    return "\n".join(lines) + "\n"


def current() -> dict:
    setuptools = tomllib.loads(PYPROJECT.read_text(encoding="utf-8")).get("tool", {}).get("setuptools", {})
    return {
        "packages": setuptools.get("packages", []),
        "py-modules": setuptools.get("py-modules", []),
        "package-dir": setuptools.get("package-dir", {}),
    }


def check() -> int:
    exp, cur = expected(), current()
    problems = []
    for key in ("packages", "py-modules"):
        missing = sorted(set(exp[key]) - set(cur[key]))
        extra = sorted(set(cur[key]) - set(exp[key]))
        problems += [f"{key}: missing {name}" for name in missing]
        problems += [f"{key}: not on disk {name}" for name in extra]
    for name, path in exp["package-dir"].items():
        if cur["package-dir"].get(name) != path:
            problems.append(f"package-dir: {name!r} should be {path!r}, is {cur['package-dir'].get(name)!r}")
    for name in sorted(set(cur["package-dir"]) - set(exp["package-dir"])):
        problems.append(f"package-dir: {name!r} is not a package on disk")
    if problems:
        print("pyproject.toml does not match the stage code folders:")
        print("\n".join(f"  {p}" for p in problems))
        print("Run:  uv run python tools/list_packages.py --write   then  uv lock")
        return 1
    print(f"pyproject.toml maps all {len(exp['packages'])} packages and {len(exp['py-modules'])} modules.")
    return 0


def write() -> int:
    text = PYPROJECT.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", re.DOTALL)
    if not pattern.search(text):
        print(f"pyproject.toml has no generated block (expected the line {BEGIN!r}).")
        return 1
    PYPROJECT.write_text(pattern.sub(lambda _: render(), text, count=1), encoding="utf-8", newline="\n")
    return check()


def import_all() -> int:
    """Import every mapped name from the installed environment, not from the source folders."""
    import importlib
    import traceback

    # Drop this script's folder, the working directory and the source-tree path ppsi_paths was
    # loaded from, so only the installed package map can satisfy an import.
    here = str(Path(__file__).resolve().parent)
    source_code = str(REPO_ROOT / "00_common" / "code")
    sys.path[:] = [p for p in sys.path if p not in ("", here, str(REPO_ROOT), source_code)]
    exp = expected()
    names = exp["packages"] + exp["py-modules"]
    failed = []
    for name in names:
        try:
            module = importlib.import_module(name)
        except Exception as exc:  # noqa: BLE001  (report every failure, then fail once)
            failed.append(name)
            print(f"FAIL {name}: {type(exc).__name__}: {exc}")
            traceback.print_exc(limit=3)
            continue
        where = getattr(module, "__file__", None) or list(getattr(module, "__path__", []))
        expected_dir = REPO_ROOT / exp["package-dir"].get(name, exp["package-dir"].get("", ""))
        location = Path(where if isinstance(where, str) else where[0]).resolve()
        if not location.is_relative_to(expected_dir.resolve()):
            failed.append(name)
            print(f"FAIL {name}: imported from {location}, expected under {expected_dir}")
    print(f"imported {len(names) - len(failed)} of {len(names)} names")
    return 1 if failed else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="exit 1 when pyproject.toml is out of date")
    mode.add_argument("--write", action="store_true", help="rewrite the generated block in pyproject.toml")
    mode.add_argument("--names", action="store_true", help="print every importable name, one per line")
    mode.add_argument("--import", dest="import_all", action="store_true",
                      help="import every name from the installed environment and report failures")
    args = parser.parse_args(argv)
    if args.check:
        return check()
    if args.write:
        return write()
    if args.import_all:
        return import_all()
    if args.names:
        exp = expected()
        print("\n".join(exp["packages"] + exp["py-modules"]))
        return 0
    sys.stdout.write(render())
    for note in discover()[2]:
        print(f"# {note}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
