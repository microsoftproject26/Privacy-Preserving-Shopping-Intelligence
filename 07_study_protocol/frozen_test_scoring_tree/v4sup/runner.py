"""The phase runner (package 10 S4; package 08 S7 "milestone monitoring"; package 13 "final state
generated by scripts").

`Supervisor.run_phase(phase_id)` makes ONE deterministic pass over a phase:
  1. already DONE/FAILED/BLOCKED -> return that state unchanged (idempotent).
  2. every `depends_on` phase DONE? if one FAILED/BLOCKED -> this phase is BLOCKED (stopped) for
     good; if one is merely not yet DONE -> WAITING_DEPENDENCY (try again later).
  3. every prerequisite gate file exists and its hash matches (`gate.check_gates`)? if not ->
     WAITING_GATE -- the phase never starts.
  4. GPU ownership fail-closed and both disk thresholds (`gpu.gpu_ready`, `disk.disk_check`)? if
     not -> QUEUED_RESOURCE -- the phase never starts.
  5. run exactly one subprocess attempt (attempt count persisted in the status file across calls),
     capture its exit code, and validate every expected artifact (`artifacts.validate_artifacts`).
     DONE only on exit code 0 AND all artifacts valid. Otherwise, if attempts remain -> retry next
     call; if attempts are exhausted -> FAILED, and every phase that depends on this one is
     immediately marked BLOCKED (package 10 S4: "a second failure sets the state FAILED and stops
     dependent phases").

No step here loops or sleeps: a phase that is not ready simply reports why and expects to be asked
again (by `run_all`, a cron entry, or a systemd timer on the server) -- this keeps every unit of
work in this module fast, bounded and directly testable with no timing dependence. `run_all` is
the thin outer loop that ties phases together for unattended, "detached" operation.
"""
from __future__ import annotations

import os
import shutil
import subprocess
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable

from .artifacts import validate_artifacts
from .disk import disk_check
from .gate import check_gates
from .gpu import default_runner as default_gpu_runner
from .gpu import gpu_ready
from .registry import Phase
from .shell import build_shell_argv
from .status import append_event, merge_status, read_status, utc, write_status_atomic

TERMINAL_STATES = ("DONE", "FAILED", "BLOCKED")


@dataclass
class SupervisorConfig:
    workspace_root: Path
    registry: "dict[str, Phase]"
    status_path: Path
    event_log_path: Path
    logs_dir: Path
    disk_usage_fn: "Callable | None" = None   # default shutil.disk_usage
    gpu_runner: "Callable | None" = None      # default nvidia-smi subprocess.run
    sleep_fn: "Callable[[float], None]" = time.sleep
    poll_interval_s: float = 5.0
    env: dict = field(default_factory=lambda: dict(os.environ))


class Supervisor:
    def __init__(self, cfg: SupervisorConfig):
        self.cfg = cfg
        self.workspace_root = Path(cfg.workspace_root).resolve()
        self.disk_usage_fn = cfg.disk_usage_fn or shutil.disk_usage
        self.gpu_runner = cfg.gpu_runner or default_gpu_runner
        self.workspace_root.mkdir(parents=True, exist_ok=True)
        Path(cfg.logs_dir).mkdir(parents=True, exist_ok=True)

    # ---- status plumbing -----------------------------------------------------------
    def _status(self) -> dict:
        return read_status(self.cfg.status_path) or {"created_utc": utc(), "phases": {}}

    def _set_phase_state(self, phase_id: str, **fields) -> None:
        s = self._status()
        s.setdefault("phases", {})
        cur = dict(s["phases"].get(phase_id, {}))
        cur.update(fields)
        s["phases"][phase_id] = cur
        s["updated_utc"] = utc()
        write_status_atomic(self.cfg.status_path, s)

    def heartbeat(self, current_phase: "str | None" = None) -> None:
        """Liveness only -- never asserts completion (package 10 S4)."""
        updates = {"heartbeat_utc": utc()}
        if current_phase is not None:
            updates["current_phase"] = current_phase
        merge_status(self.cfg.status_path, **updates)

    def phase_state(self, phase_id: str) -> str:
        return (self._status().get("phases", {}).get(phase_id) or {}).get("state", "PENDING")

    def phase_status(self, phase_id: str) -> dict:
        return dict(self._status().get("phases", {}).get(phase_id) or {})

    # ---- readiness ------------------------------------------------------------------
    def resource_check(self, phase: Phase) -> "tuple[bool, str]":
        ok, why = gpu_ready(phase.gpus, self.gpu_runner)
        if not ok:
            return False, f"GPU: {why}"
        dd = disk_check(self.workspace_root, phase.planned_peak_gib, self.disk_usage_fn)
        if dd.state != "OK":
            return False, f"DISK {dd.state}: {dd.reason}"
        return True, dd.reason

    def _dependency_state(self, phase: Phase) -> "tuple[str, str]":
        """Returns ("ready"|"waiting"|"blocked", reason)."""
        for dep in phase.depends_on:
            dstate = self.phase_state(dep)
            if dstate in ("FAILED", "BLOCKED"):
                return "blocked", f"dependency {dep!r} is {dstate}"
            if dstate != "DONE":
                return "waiting", f"dependency {dep!r} not DONE (state={dstate})"
        return "ready", "ok"

    # ---- one subprocess attempt -------------------------------------------------------
    def _build_argv(self, phase: Phase) -> "list[str]":
        if phase.command:
            return list(phase.command)
        return build_shell_argv(phase.shell_command)

    def _run_attempt(self, phase: Phase, attempt: int) -> "tuple[int, Path]":
        log_dir = Path(self.cfg.logs_dir) / phase.id
        log_dir.mkdir(parents=True, exist_ok=True)
        log_path = log_dir / f"attempt_{attempt}.log"
        argv = self._build_argv(phase)
        with open(log_path, "a", encoding="utf-8") as lf:
            lf.write(f"[{utc()}] START {argv!r}\n")
            lf.flush()
            t0 = time.time()
            try:
                proc = subprocess.Popen(argv, cwd=str(self.workspace_root), env=self.cfg.env,
                                         stdout=lf, stderr=subprocess.STDOUT)
                rc = proc.wait(timeout=phase.timeout_s)
            except subprocess.TimeoutExpired:
                proc.kill()
                proc.wait()
                rc = -9
                lf.write(f"[{utc()}] TIMEOUT after {phase.timeout_s}s, killed\n")
            except OSError as e:
                rc = -1
                lf.write(f"[{utc()}] EXEC ERROR {e}\n")
            lf.write(f"[{utc()}] END rc={rc} wall={time.time() - t0:.1f}s\n")
        return rc, log_path

    # ---- one phase, one deterministic pass --------------------------------------------
    def run_phase(self, phase_id: str) -> str:
        phase = self.cfg.registry[phase_id]
        cur = self.phase_state(phase_id)
        if cur in TERMINAL_STATES:
            return cur

        dep_state, dep_reason = self._dependency_state(phase)
        if dep_state == "blocked":
            self._set_phase_state(phase_id, state="BLOCKED", reason=dep_reason)
            append_event(self.cfg.event_log_path, {"phase": phase_id, "event": "blocked", "reason": dep_reason})
            return "BLOCKED"
        if dep_state == "waiting":
            self._set_phase_state(phase_id, state="WAITING_DEPENDENCY", reason=dep_reason)
            return "WAITING_DEPENDENCY"

        gr = check_gates(phase.prerequisites)
        if not gr.ok:
            self._set_phase_state(phase_id, state="WAITING_GATE", reason=gr.reason)
            append_event(self.cfg.event_log_path, {"phase": phase_id, "event": "gate_not_ready", "reason": gr.reason})
            return "WAITING_GATE"

        ok, why = self.resource_check(phase)
        if not ok:
            self._set_phase_state(phase_id, state="QUEUED_RESOURCE", reason=why)
            append_event(self.cfg.event_log_path, {"phase": phase_id, "event": "queued_resource", "reason": why})
            return "QUEUED_RESOURCE"

        attempts_used = int(self.phase_status(phase_id).get("attempts_used", 0))
        attempt = attempts_used + 1
        self._set_phase_state(phase_id, state="RUNNING", attempt=attempt, reason=None)
        append_event(self.cfg.event_log_path, {"phase": phase_id, "event": "attempt_start", "attempt": attempt})

        rc, log_path = self._run_attempt(phase, attempt)
        good, checks = (False, ()) if rc != 0 else validate_artifacts(self.workspace_root, phase.expected_artifacts)
        done = (rc == 0) and good
        append_event(self.cfg.event_log_path, {"phase": phase_id, "event": "attempt_end", "attempt": attempt,
                                               "rc": rc, "done": done, "log": str(log_path),
                                               "artifact_checks": [c.__dict__ for c in checks]})

        if done:
            self._set_phase_state(phase_id, state="DONE", attempts_used=attempt, rc=rc, end_utc=utc(),
                                  log=str(log_path), reason=None)
            return "DONE"

        reason = "exit_nonzero" if rc != 0 else "artifacts_invalid"
        if attempt >= phase.max_attempts:
            self._set_phase_state(phase_id, state="FAILED", attempts_used=attempt, rc=rc, reason=reason,
                                  log=str(log_path), end_utc=utc())
            append_event(self.cfg.event_log_path, {"phase": phase_id, "event": "failed", "attempts_used": attempt,
                                                    "max_attempts": phase.max_attempts, "reason": reason})
            self._stop_dependents(phase_id)
            return "FAILED"

        self._set_phase_state(phase_id, state="ATTEMPT_FAILED", attempts_used=attempt, rc=rc, reason=reason,
                              log=str(log_path))
        return "ATTEMPT_FAILED"

    def _stop_dependents(self, failed_id: str) -> None:
        for pid, phase in self.cfg.registry.items():
            if failed_id in phase.depends_on and self.phase_state(pid) not in TERMINAL_STATES:
                reason = f"dependency {failed_id!r} FAILED"
                self._set_phase_state(pid, state="BLOCKED", reason=reason)
                append_event(self.cfg.event_log_path, {"phase": pid, "event": "blocked", "reason": reason})

    # ---- the whole registry, unattended -----------------------------------------------
    def run_all(self, order: "list[str] | None" = None, max_rounds: int = 100000) -> dict:
        """Repeatedly calls `run_phase` for every non-terminal phase until every phase reaches a
        terminal state, or `max_rounds` passes make no progress at all (a safety bound; tests pass
        a small value and a fake `sleep_fn`, production leaves the default and a real
        `time.sleep`). Returns the final status dict."""
        order = order or list(self.cfg.registry.keys())
        for _ in range(max_rounds):
            pending = [pid for pid in order if self.phase_state(pid) not in TERMINAL_STATES]
            if not pending:
                break
            self.heartbeat()
            progressed = False
            for pid in pending:
                before = self.phase_state(pid)
                after = self.run_phase(pid)
                if after != before:
                    progressed = True
            if not progressed:
                self.cfg.sleep_fn(self.cfg.poll_interval_s)
        return self._status()
